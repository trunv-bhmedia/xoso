    <h2>Hướng dẫn chơi: </h2>
    <strong>1.Tham gia dự thưởng 1 số theo các bước sau:</strong><br>
    - Bước 1: Dùng bút chì chọn số trên thẻ chọn số tại Điểm bán hàng.<br>
    + Chọn 1 số có 4 chữ số để tạo thành 1 số tham gia dự thưởng từ 0000 đến 9999. (*)<br>
    Ví dụ: <br>
    Bạn muốn chọn số 0241, bạn đánh dấu vào thẻ chọn như hình sau:<br>

    Lưu ý: bạn chỉ được chọn 1 chữ số tại mỗi cột từ 0 đến 9.<br>
    + Hoặc đánh dấu vào ô TC cuối mỗi bảng chọn để máy tính chọn ngẫu nhiên số may mắn cho bạn.<br>

    - Bước 2: Chọn mệnh giá tham gia dự thưởng<br>
    Mỗi số dự thưởng có giá 10.000 đồng. Tuy nhiên, nếu bạn muốn có cơ hội trúng giải lớn hơn, bạn có thể chọn các mệnh giá tham gia dự thưởng khác nhau. Với mỗi số trong 1 lần chọn trên thẻ chọn số, bạn có thể tham gia dự thưởng tối đa 1.000.000 VNĐ (một triệu đồng).<br>
    Ví dụ: Bạn tham gia dự thưởng bộ số 0241 với mệnh giá 20.000 VNĐ và trúng giải Nhất, bạn sẽ nhận được giải thưởng trị giá cao gấp 2 lần giá trị giải Nhất.<br>

    - Bước 3: Đưa thẻ cho nhân viên bán hàng và thanh toán.<br>
    - Bước 4: Nhận lại vé và kiểm tra lại thông tin.<br>
    (*) Khi có quá nhiều người cùng mua 1 số tham gia dự thưởng, Vietlott có quyền dừng phát hành số tham gia dự thưởng đó và nhân viên bán hàng sẽ thông báo tại các điểm bán hàng khi người chơi mua vé dự thưởng.<br>

    <strong>2.Tham gia dự thưởng nhiều số:</strong><br>
    - Mỗi thẻ chọn số có 6 bảng chọn A, B, C, D, E, F. Mỗi bảng chọn tương ứng với 1 số tham gia dự thưởng. Hãy chọn số trong nhiều bảng để nhận thêm nhiều cơ hội trúng thưởng hơn.<br>
    Ví dụ: <br>
    Bạn muốn tham gia dự thưởng 2 số 1318 và 1047, bạn đánh dấu vào thẻ chọn số như hình sau:<br>

    <strong>3.Tham gia dự thưởng nhiều kỳ:</strong><br>
    Nếu bạn muốn tham gia dự thưởng một số trong nhiều kỳ liên tiếp, bạn có thể chọn số kỳ như trong hình dưới đây. Bạn có thể dự thưởng tối đa 6 kỳ liên tiếp.<br>

